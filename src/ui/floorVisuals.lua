  local xml, pieces, layout, mapCode
  local viewers = {}
  local defaultFriction = {[1]=0,[2]=0,[3]=0,[4]=20,[7]=0.1,[9]=0,[11]=0.05,[15]=0,[21]=0}
  local defaultRestitution = {[2]=1.2,[3]=20,[9]=0,[10]=0,[11]=0.1,[15]=0,[19]=0,[20]=0,[21]=0}

  function floorVisuals.newGame()
    -- The engine has already discarded the previous map's images.
    xml, pieces, layout, mapCode, viewers = nil, nil, nil, nil, {}
  end

  function floorVisuals.clearPlayer(name)
    for _, id in ipairs(viewers[name] or {}) do tfm.exec.removeImage(id) end
    viewers[name] = nil
  end

  -- Numeric keys avoid host-dependent number-to-string formatting.
  local function normalizeCode(value)
    if type(value) == 'string' then
      value = value:match('^%s*@?(%d+)%s*$') or value:match('^%s*@?(%d+)%.0+%s*$')
      value = value and tonumber(value)
    end
    if type(value) == 'number' and value > 0 and value < math.huge
        and value == math.floor(value) then return value end
  end

  function floorVisuals.setXML(value, code, sourceCode)
    code = normalizeCode(code) or normalizeCode(sourceCode)
    if xml == value and mapCode == code then return end
    local names = {}
    for name in pairs(viewers) do names[#names+1] = name end
    for _, name in ipairs(names) do floorVisuals.clearPlayer(name) end
    xml, pieces, layout, mapCode = value, nil, nil, code
  end

  local function number(value, default)
    if value == nil then return default end
    local n = tonumber(value)
    if n and n > -math.huge and n < math.huge then return n end
  end

  local function physics(value, kind)
    -- Defaults follow the native platform type. Missing trailing fields keep
    -- their defaults; an omitted P is not treated as eight physical zeroes.
    local p = {0,0,defaultFriction[kind] or 0.3,defaultRestitution[kind] or 0.2,0,0,0,0}
    if value ~= nil then
      local i = 0
      for part in (value .. ','):gmatch('(.-),') do
        i = i + 1
        if i > 8 then return end
        if part ~= '' then
          local n = number(part)
          if not n then return end
          p[i] = n
        end
      end
    end
    return p
  end

  local function ground(a)
    local x = number(a.X, 0)
    local candidates = x and floorVisuals.groundsByX[x]
    if not candidates then return end
    local kind, y, w = number(a.T, 0), number(a.Y, 0), number(a.L, 10)
    local h = kind == 13 and 0 or number(a.H, 10)
    local collision = number(a.c, kind == 8 and 2 or 1)
    if not kind or not y or not w or not h or not collision or w <= 0 or (kind ~= 13 and h <= 0) then return end
    -- Native c=0/c=1 both collide with mice and objects; absent c uses the
    -- platform default (Cloud is object-only). Preserve other collision modes.
    if collision == 0 then collision = 1 end
    local p
    for _, entry in ipairs(candidates) do
      if entry[3] == kind and entry[4] == y and entry[5] == w
          and entry[6] == h and entry[7] == collision then
        if not p then
          p = physics(a.P, kind)
          if not p or p[1] ~= 0 then return end
        end
        local same = true
        for i=1,8 do
          if entry[7+i] ~= p[i] then same = false; break end
        end
        if same then return entry, x, p end
      end
    end
  end

  local function materialType(kind, p)
    if kind ~= 12 and kind ~= 14 then return kind end
    if p[4] >= 1 then return 2 end
    if p[3] <= 0.05 then return 1 end
    if p[3] >= 1 then return 4 end
    return 0
  end

  local function validLayout(value)
    return type(value) == 'table' and type(value[1]) == 'string' and value[1] ~= ''
      and type(value[2]) == 'number' and value[2] > -math.huge and value[2] < math.huge
      and type(value[3]) == 'number' and value[3] > -math.huge and value[3] < math.huge
  end

  local function geometry()
    if pieces then return pieces end
    pieces = {}
    local ids = {}
    local corrected = mapCode and floorVisuals.maps[mapCode]
    local allowed, correctedIds
    if validLayout(corrected) and type(corrected[4]) == 'string' and corrected[4] ~= '' then
      allowed, correctedIds = {}, {}
      for id in corrected[4]:gmatch('%d+') do allowed[tonumber(id)] = true end
    end
    local grounds = (xml or ''):match('<S>(.-)</S>') or ''
    for tag in grounds:gmatch('<S%s+([^>]+)>') do
      local a = {}
      for k, quote, value in tag:gmatch('([%w_]+)%s*=%s*([\'"])(.-)%2') do a[k] = value end
      local entry, x, p = ground(a)
      if entry then
        local id, kind = entry[1], entry[3]
        if entry[2] == 1 and kind ~= 13 and (a.m ~= nil or kind == 14) then
          pieces[#pieces+1] = {x, entry[4], entry[5], entry[6], p[5]*math.pi/180, materialType(kind,p)}
          ids[#ids+1] = id
        end
        if allowed and allowed[id] then correctedIds[#correctedIds+1] = id end
      end
    end
    if correctedIds and table.concat(correctedIds, ';') == corrected[4] then
      layout = corrected
    elseif #pieces > 0 then
      local uploaded = floorVisuals.layouts[table.concat(ids, ';')]
      if validLayout(uploaded) then layout = uploaded end
    end
    return pieces
  end

  function floorVisuals.show(name)
    if not name or not tfm.get.room.playerList[name] or viewers[name] or not xml then return end
    local ids = {}
    local grounds = geometry()
    if layout then
      local id = tfm.exec.addImage(layout[1], '?1001', layout[2], layout[3], name,
        1, 1, 0, 1, 0, 0)
      if id then ids[1] = id end
    else
      for _, p in ipairs(grounds) do
        local asset, w, h = floorVisuals.image, 32, 32
        local material = floorVisuals.materials[p[6]]
        if material and material[1] and material[1] ~= '' then
          asset, w, h = material[1], material[2], material[3]
        end
        if asset and asset ~= '' then
          local id = tfm.exec.addImage(asset, '?1001', p[1], p[2], name,
            p[3]/w, p[4]/h, p[5], 1, 0.5, 0.5)
          if id then ids[#ids+1] = id end
        end
      end
    end
    viewers[name] = ids
  end
