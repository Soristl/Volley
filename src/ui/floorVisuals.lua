      local signature = table.concat(key, '|')
      if (volleyGroundSignatures[signature] or visualOnlyGrounds[signature]) and (a.m ~= nil or a.T == '14') then
        local p = {}
        for value in ((a.P or '') .. ','):gmatch('(.-),') do p[#p+1] = tonumber(value) or 0 end
        local x, y, w, h = tonumber(a.X), tonumber(a.Y), tonumber(a.L), tonumber(a.H)
        if x and y and w and h and w > 0 and h > 0 and (p[1] or 0) == 0 then
          pieces[#pieces+1] = {x, y, w, h, (p[5] or 0)*math.pi/180, materialType(tonumber(a.T), p)}
          signatures[#signatures+1] = signature
        end
      end
    end
    if #pieces > 0 then
      local uploaded = floorVisuals.layouts[table.concat(signatures, ';')]
      if type(uploaded) == 'table' and type(uploaded[1]) == 'string' and uploaded[1] ~= ''
          and type(uploaded[2]) == 'number' and uploaded[2] > -math.huge and uploaded[2] < math.huge
          and type(uploaded[3]) == 'number' and uploaded[3] > -math.huge and uploaded[3] < math.huge then
        layout = {uploaded[1], uploaded[2], uploaded[3]}
      end
    end
    return pieces
  end

